// One-off generator for app/africa.js: African country shapes + flags for the motion story.
//   Shapes: Natural Earth 1:50m via world-atlas@2.0.2 (public domain).
//   Flags:  flag-icons@7.2.3, 4x3 SVGs (MIT, (c) Panayiotis Lipiridis).
// Usage: node scripts/build-geo.mjs <path-to-node_modules containing world-atlas, topojson-client, flag-icons>
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NM = path.resolve(process.argv[2] || "node_modules");
const require = createRequire(path.join(NM, "x.js"));
const topojson = require("topojson-client");
const topo = JSON.parse(fs.readFileSync(path.join(NM, "world-atlas", "countries-50m.json"), "utf8"));

// ISO 3166 numeric codes of African states (+ Western Sahara); Somaliland has no code in Natural Earth, so match by name.
const AFRICA = new Set(("012 024 072 108 120 132 140 148 174 178 180 204 226 231 232 262 266 270 288 324 384 404 426 430 434 450 454 466 478 480 504 508 516 " +
  "562 566 624 646 678 686 690 694 706 710 716 728 729 732 748 768 788 800 818 834 854 894").split(" "));
// cohort countries: name used in the data -> ISO alpha-2 (flag file)
const HOME = { Uganda: "ug", Kenya: "ke", Egypt: "eg", Nigeria: "ng", Malawi: "mw", Ethiopia: "et", Ghana: "gh", Morocco: "ma", Sudan: "sd", Tanzania: "tz", Cameroon: "cm" };

const round = (c) => (typeof c[0] === "number" ? [Math.round(c[0] * 20) / 20, Math.round(c[1] * 20) / 20] : c.map(round));
const dedupe = (ring) => ring.filter((p, i) => i === 0 || p[0] !== ring[i - 1][0] || p[1] !== ring[i - 1][1]);
const clean = (g) => {
  const polys = (g.type === "Polygon" ? [g.coordinates] : g.coordinates).map((poly) => round(poly).map(dedupe).filter((r) => r.length >= 4));
  const kept = polys.filter((p) => p.length);
  return kept.length === 1 ? { type: "Polygon", coordinates: kept[0] } : { type: "MultiPolygon", coordinates: kept };
};

const all = topojson.feature(topo, topo.objects.countries).features;
// Morocco is shown as one shape that includes Western Sahara (team decision, 27 Nov): dissolve the two with topojson.merge so no border line is drawn between them.
const geoms = topo.objects.countries.geometries;
const moroccoMerged = topojson.merge(topo, geoms.filter((g) => g.id === "504" || g.id === "732"));
const features = all.filter((f) => (AFRICA.has(f.id) || f.properties.name === "Somaliland") && f.id !== "732")
  .map((f) => ({ type: "Feature", properties: { name: f.properties.name }, geometry: clean(f.id === "504" ? moroccoMerged : f.geometry) }));
for (const name of Object.keys(HOME)) if (!features.some((f) => f.properties.name === name)) throw new Error("missing shape: " + name);

const flags = {};
for (const [name, iso] of Object.entries(HOME)) {
  const svg = fs.readFileSync(path.join(NM, "flag-icons", "flags", "4x3", iso + ".svg"), "utf8").trim();
  flags[name] = "data:image/svg+xml;base64," + Buffer.from(svg).toString("base64");
}

const out = `// Generated by scripts/build-geo.mjs. Shapes: Natural Earth 1:50m (public domain) via world-atlas.
// Flags: flag-icons (MIT, (c) Panayiotis Lipiridis).
window.AFRICA_GEO = ${JSON.stringify({ type: "FeatureCollection", features })};
window.AFRICA_FLAGS = ${JSON.stringify(flags)};
`;
fs.writeFileSync(path.join(ROOT, "app", "africa.js"), out);
console.log("app/africa.js", features.length, "shapes", (out.length / 1024).toFixed(1) + " KB");
