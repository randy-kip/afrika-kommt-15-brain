// Builds the full presentation deck and the page hub:
//   release/deck/index.html   (from app/deck.html)
//   release/deck/facts.js     window.DECK_FACTS from restricted/context/09-fellow-facts.json (one fun + one serious fact per fellow)
//                             and window.DECK_PHOTOS for every release/deck/photos/<id>.jpg that exists
//   release/hub/index.html    (from app/hub.html): links to every page
// Usage: node scripts/build-deck.mjs   (run node scripts/export.mjs release first)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rel = (...p) => path.join(ROOT, "release", ...p);
fs.mkdirSync(rel("deck", "photos"), { recursive: true });
fs.mkdirSync(rel("hub"), { recursive: true });
// cache-bust the data scripts so a presenter never gets yesterday's photos or map (Pages caches for 10 min)
const V = Date.now().toString(36);
fs.writeFileSync(rel("deck", "index.html"), fs.readFileSync(path.join(ROOT, "app", "deck.html"), "utf8").replace(/src="((?:\.\.\/)?[a-z]+\.js)"/g, (m, f) => `src="${f}?v=${V}"`));
fs.copyFileSync(path.join(ROOT, "app", "hub.html"), rel("hub", "index.html"));

const factsPath = path.join(ROOT, "restricted", "context", "09-fellow-facts.json");
const raw = fs.existsSync(factsPath) ? JSON.parse(fs.readFileSync(factsPath, "utf8")) : {};
const facts = {};
for (const [id, f] of Object.entries(raw)) facts[id] = { short: f.short, fun: f.fun ?? null, serious: f.serious ?? null };
const photos = {};
for (const file of fs.readdirSync(rel("deck", "photos")).sort()) {
  const m = file.match(/^(F\d{2})\.jpg$/);
  if (m) photos[m[1]] = "photos/" + file;
}
const js = `// Generated by scripts/build-deck.mjs. Facts reviewed by the team before the talk.\nwindow.DECK_FACTS = ${JSON.stringify(facts, null, 1)};\nwindow.DECK_PHOTOS = ${JSON.stringify(photos, null, 1)};\n`;
if (/<\/script|@[a-z0-9.-]+\.[a-z]{2,}|https?:\/\//i.test(js)) throw new Error("facts.js contains a URL, email or </script>");
fs.writeFileSync(rel("deck", "facts.js"), js);
console.log("deck: facts", Object.keys(facts).length, "photos", Object.keys(photos).length);
